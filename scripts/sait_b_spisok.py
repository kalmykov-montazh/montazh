#!/usr/bin/env python3
# 17.11.2026: список для sait-b.yml по роликам без окошка сайта (из отчёта scripts/est_okoshko.py).
# Тема берётся из названия ролика — правило «Монтаж — ГЛАВНАЯ ВЕРСИЯ…», замок 2 (тексты — как в утверждённых 14.11).
#   python3 sait_b_spisok.py отчёт.txt > hf/sait_skriny/sait_b_1711.json
import sys, json, re
T = [
    (r'ВНЖ|защит|прописк|сотрудник|документ|гражданств|автономо|аутономо|бекх|налог', 'usl_yuristy.png',
     'Документы и ВНЖ — проверенные юристы. Ссылка в шапке профиля'),
    (r'повышени\w* аренд|залог|договор|хозяин|съехать|выселен', 'razbor.png',
     'Проблема с квартирой? Разберу ваш договор. Ссылка в шапке профиля'),
    (r'Сначала месяц|аренд|сдаёт|снять|плесень', 'chek.png',
     'Бесплатный чек-лист перед договором аренды. Ссылка в шапке профиля'),
    (r'ипотек', 'usl_ipoteka.png', 'Ипотека в Испании? Подключу проверенного брокера. Ссылка в шапке профиля'),
    (r'купить|квартир|этаж|район|наводнен', 'usl_kupit.png', 'Купить или продать квартиру — пишите. Ссылка в шапке профиля'),
    (r'НОВОСТЬ|новост', 'novosti.png', 'Новости Испании каждый день. Ссылка в шапке профиля'),
    (r'газ|страховк|полиц|европротокол|машин', 'usl_yuristy.png',
     'Уже в Испании? Юристы, ипотека, жильё — проверенные люди. Ссылка в шапке профиля'),
]
DEF = ('shapka.png', 'Собираетесь переезжать в Испанию? Всё полезное — на моём сайте. Ссылка в шапке профиля')
out = []
for line in open(sys.argv[1], encoding='utf-8'):
    if not line.startswith('нет'): continue
    f = line.rstrip('\n').split('\t', 1)[1]
    name = f.split('/')[-2]
    img, text = DEF
    for rx, i, t in T:
        if re.search(rx, name, re.I): img, text = i, t; break
    out.append({'f': f, 'g': '', 'img': img, 'text': text, 'name': name})
print(json.dumps(out, ensure_ascii=False, indent=1))
