import json
ch=json.load(open('chunks.json'))
DROP=set([11,98,99,100,101,132,133,336]+list(range(345,365)))
PL,PR=0.10,0.15
segs=[[a-PL,b+PR] for i,(a,b) in enumerate(ch) if i not in DROP]
segs.sort();m=[]
for s,e in segs:
    if m and s<=m[-1][1]: m[-1][1]=max(m[-1][1],e)
    else: m.append([s,e])
q=lambda t: round(t*60)/60
body=[[q(max(0,s)),q(e)] for s,e in m if e-s>0.1]
hook=[[q(118.6),q(125.05)],[q(1139.8),q(1145.05)],[q(893.2),q(899.35)]]
HCAP=[('Телефон в руке','200 евро штрафа'),('Наличными больше 1000','штраф 25% обоим'),('Плюнули на улице','до 3000 евро')]
# close-up windows in raw time (chunk starts/ends) with plaque text
WR=[(12.2,29.1,'15 законов, за которые наши платят штрафы'),
(64.2,74.1,'Законы меняются — проверяйте цифры'),
(100.4,112.9,'Камеры и дроны ловят без полиции'),
(153.7,167.6,'Фиксируют и машины в гражданском'),
(180.3,192.9,'Нет полиции рядом — не значит можно'),
(285.5,303.3,'Маячок обязателен, треугольники — по желанию'),
(326.7,338.6,'Сзади тоже пристёгиваемся'),
(466.4,497.7,'Я сам ставил машину на испанский учёт'),
(638.4,655.7,'Страховка в разы дешевле штрафа'),
(721.9,731.5,'Это суд, а не квитанция'),
(830.5,847.2,'С собакой — бутылка воды обязательно'),
(860.5,871.0,'Правила по Валенсии с 15 июня 2026'),
(947.1,973.0,'Старую мебель город вывозит бесплатно'),
(1057.5,1070.1,'Следите за сроком ВНЖ'),
(1145.2,1164.8,'Больше 1000 евро — только безнал'),
(1455.3,1466.1,'Оплатили со скидкой — оспорить нельзя'),
(1493.6,1501.9,'Сколько из 15 вы знали?'),
(1502.5,1527.1,'Пишите в личку — дам контакты'),
(1527.5,1534.0,None)]
SUBR=[135.0,705.0,1385.0]
def tb(t):  # raw -> body time
    o=0.0
    for s,e in body:
        if t<s: return o
        if t<=e: return o+t-s
        o+=e-s
    return o
W=[(tb(a-PL),tb(b+PR),t) for a,b,t in WR]
SUB=[tb(t) for t in SUBR]
H=sum(e-s for s,e in hook); BL=sum(e-s for s,e in body)
json.dump({'body':body,'hook':hook,'hcap':HCAP,'W':W,'SUB':SUB,'H':H,'BL':BL},open('plan.json','w'),ensure_ascii=False)
print('hook',H,'body',BL,'final ~',(H+74/60+BL)/1.2/60,'cam share',sum(b-a for a,b,_ in W)/BL)
print([round(x,1) for x in SUB],[round((H+74/60+x)/1.2,1) for x in SUB])
