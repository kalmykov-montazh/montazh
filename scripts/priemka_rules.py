# Правила приёмки (17.11.2026): какие замечания проверки на слух — брак (карантин), а какие — разобрать вручную.
# Подобрано по прогону всех неопубликованных роликов 17.11.2026 ночью: живая речь сама повторяет слова
# («может быть… может быть», «нота симпля, нота симпля»), а Whisper растягивает слова перед паузой — это не брак.
# Брак — неудачный дубль: команда «заново / со слов», лишний кусок речи, который общая расшифровка проглотила,
# повтор фразы из 4+ слов подряд, срез слова на стыке, срезанное начало или конец.
# Запуск: python3 priemka_rules.py otchet.json  → печатает «ЖЁСТКО …» и «мягко …»
import json, sys

def classify(flags):
    near = lambda f, kinds, r=3.0: any(g is not f and g['kind'] in kinds and abs(g['t'] - f['t']) <= r for g in flags)
    hard, soft = [], []
    for f in flags:
        if not f.get('strong'): continue
        k = f['kind']
        if 'субтитр' in f['why'].lower() or 'dimatorzok' in f['why'].lower():
            continue   # выдумка Whisper на музыке
        if k in ('НАЧАЛО', 'КОНЕЦ'):
            # «громко в первом/последнем кадре» само по себе бывает и у целого слова; брак — если там же слово не слышно
            (hard if near(f, ('СЛОВО', 'СТЫК', 'ОБРЫВ'), 1.5) else soft).append(f)
        elif k in ('СЛУЖЕБНОЕ', 'ЛИШНЯЯ РЕЧЬ', 'СТЫК', 'СТЫК-В-РЕЧИ', 'ОБРЫВ', 'РЕЗ ПО СЛОВУ'):
            hard.append(f)
        elif k == 'ФАЛЬСТАРТ':
            # дубль, если рядом ещё один признак (команда, лишняя речь, растянутое слово)
            (hard if near(f, ('СЛУЖЕБНОЕ', 'ЛИШНЯЯ РЕЧЬ', 'РЕЗИНОВОЕ СЛОВО')) else soft).append(f)
        elif k == 'ПОВТОР':
            n = len(f['why'].split('»')[0].split())
            (hard if n >= 4 or near(f, ('СЛУЖЕБНОЕ', 'ЛИШНЯЯ РЕЧЬ')) else soft).append(f)
        elif k == 'РЕЗИНОВОЕ СЛОВО':
            if near(f, ('ЛИШНЯЯ РЕЧЬ', 'СЛУЖЕБНОЕ', 'ФАЛЬСТАРТ')): hard.append(f)
            # одиночное растянутое слово — почти всегда пауза после слова, не брак: не показываем
        else:
            soft.append(f)
    return hard, soft

if __name__ == '__main__':
    d = json.load(open(sys.argv[1]))
    h, s = classify(d['flags'])
    for x in h: print(f"ЖЁСТКО {x['kind']} {x['t']} с: {x['why']}")
    for x in s: print(f"мягко {x['kind']} {x['t']} с: {x['why']}")
